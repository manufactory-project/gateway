const (
	DefaultFakeCIDR            = "198.18.0.0/15"
	DefaultDNSTTLSeconds       = 60
	DefaultMaxRequestBodyBytes = 32 << 20 // 32 MiB
	DefaultWSMaxEgressBytes    = 64 << 20 // 64 MiB
	DefaultMaxHeaderBytes      = 32 << 10 // 32 KiB
	DefaultAuditRetainDays     = 30
	MaxAuditRetainDays         = int(math.MaxInt64 / int64(24*time.Hour))
	DefaultAuditMaxFileBytes   = 100 << 20 // 100 MiB
	DefaultHTTPSPort           = 10443
	DefaultHTTPPort            = 10080
	DefaultDNSPort             = 10053
	DefaultDHCPLeaseTime       = "12h"
	PlaceholderPrefix          = "mf_ph_"
)

// Config is the validated, normalized gateway configuration.
type Config struct {
	CA        CAConfig          `yaml:"ca"`
	Audit     AuditConfig       `yaml:"audit"`
	Admin     AdminConfig       `yaml:"admin"`
	Metrics   MetricsConfig     `yaml:"metrics"`
	Dataplane DataplaneConfig   `yaml:"dataplane"`
	DNS       DNSConfig         `yaml:"dns"`
	HTTP      HTTPConfig        `yaml:"http"`
	Records   map[string]string `yaml:"records"`
	Links     []LinkConfig      `yaml:"links"`
	Rules     []RuleConfig      `yaml:"rules"`

	// Parsed fields derived during validation (never serialized).
	FakePrefix    netip.Prefix          `yaml:"-"`
	ParsedRecords map[string]netip.Addr `yaml:"-"`
}

// CAConfig holds operator-supplied MITM CA file paths.
type CAConfig struct {
	CertPath string `yaml:"cert_path"`
	KeyPath  string `yaml:"key_path"`
}

// AuditConfig configures the fail-closed JSONL audit sink.
type AuditConfig struct {
	Dir          string `yaml:"dir"`
	RetainDays   int    `yaml:"retain_days"`
	MaxFileBytes int64  `yaml:"max_file_bytes"`
	StdoutJSON   bool   `yaml:"stdout_json"`
}

// AdminConfig configures the Unix-domain-socket Admin API.
type AdminConfig struct {
	Socket      string `yaml:"socket"`
	SocketGroup string `yaml:"socket_group"`
}

// MetricsConfig configures the optional explicit-bind Prometheus /metrics listener.
type MetricsConfig struct {
	Listen string `yaml:"listen"`
}

// DataplaneConfig configures Linux netsetup and startup verification.
type DataplaneConfig struct {
	VerifySysctls *bool      `yaml:"verify_sysctls"`
	ReadyFile     string     `yaml:"ready_file"`
	DHCP          DHCPConfig `yaml:"dhcp"`
}

// DHCPConfig configures the DHCP-only dnsmasq config generated by netsetup.
type DHCPConfig struct {
	User       string `yaml:"user"`
	LeaseFile  string `yaml:"lease_file"`
	ConfigPath string `yaml:"config_path"`
	LeaseTime  string `yaml:"lease_time"`
}

// DNSConfig configures fake-IP DNS.
type DNSConfig struct {
	FakeCIDR   string `yaml:"fake_cidr"`
	TTLSeconds uint32 `yaml:"ttl_seconds"`
}

// HTTPConfig configures MITM HTTP/2/WS size and header limits.
type HTTPConfig struct {
	MaxRequestBodyBytes int64 `yaml:"max_request_body_bytes"`
	WSMaxEgressBytes    int64 `yaml:"ws_max_egress_bytes"`
	MaxHeaderBytes      int   `yaml:"max_header_bytes"`
}

// LinkConfig maps one sandbox link interface and subnet to one principal.
type LinkConfig struct {
	Name       string `yaml:"name"`
	Interface  string `yaml:"interface"`
	Principal  string `yaml:"principal"`
	Subnet     string `yaml:"subnet"`
	GatewayIP  string `yaml:"gateway_ip"`
	HTTPSPort  uint16 `yaml:"https_port"`
	HTTPPort   uint16 `yaml:"http_port"`
	DNSPort    uint16 `yaml:"dns_port"`
	CTZone     uint16 `yaml:"ct_zone"`
	RouteTable int    `yaml:"route_table"`
	RoutePref  int    `yaml:"route_pref"`

	ParsedSubnet    netip.Prefix `yaml:"-"`
	ParsedGatewayIP netip.Addr   `yaml:"-"`
}

// RuleConfig is one default-deny allow or deny rule for a principal.
type RuleConfig struct {
	ID               string          `yaml:"id"`
	Principal        string          `yaml:"principal"`
	Effect           string          `yaml:"effect"`
	Hosts            []string        `yaml:"hosts"`
	Ports            []uint16        `yaml:"ports"`
	Methods          []string        `yaml:"methods"`
	Paths            []string        `yaml:"paths"`
	AllowWebSocket   bool            `yaml:"allow_websocket"`
	WSMaxEgressBytes int64           `yaml:"ws_max_egress_bytes"`
	Bindings         []BindingConfig `yaml:"bindings"`
}

// BindingConfig declares a substitution-only secret placeholder binding.
type BindingConfig struct {
	Name        string   `yaml:"name"`
	Host        string   `yaml:"host"`
	Methods     []string `yaml:"methods"`
	Paths       []string `yaml:"paths"`
	Header      string   `yaml:"header"`
	Scheme      string   `yaml:"scheme"`
	Placeholder string   `yaml:"placeholder"`
	SecretFile  string   `yaml:"secret_file"`
}

// LoadFile reads, strictly parses, normalizes, and validates a YAML config file.
// It returns the validated Config and the SHA-256 hex digest of the raw file bytes.
func LoadFile(path string) (*Config, string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, "", fmt.Errorf("config: read %s: %w", path, err)
	}
	cfg, err := Parse(data)
	if err != nil {
		return nil, "", fmt.Errorf("config: %s: %w", path, err)
	}
	sum := sha256.Sum256(data)
	return cfg, hex.EncodeToString(sum[:]), nil
}

// Parse strictly decodes YAML (rejecting unknown fields), applies defaults, and validates.
func Parse(data []byte) (*Config, error) {
	var cfg Config
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	if err := dec.Decode(&cfg); err != nil {
		if errors.Is(err, io.EOF) {
			return nil, errors.New("empty configuration")
		}
		return nil, fmt.Errorf("decode yaml: %w", err)
	}
	// Ensure no trailing second YAML document is silently ignored.
	var extra any
	if err := dec.Decode(&extra); err != nil && !errors.Is(err, io.EOF) {
		return nil, fmt.Errorf("trailing yaml document: %w", err)
	} else if err == nil {
		return nil, errors.New("multiple YAML documents are not supported")
	}

	applyDefaults(&cfg)
	if err := validate(&cfg); err != nil {
		return nil, err
	}
	return &cfg, nil
}

// ShouldVerifySysctls reports whether startup sysctl verification is enabled.
func (c *Config) ShouldVerifySysctls() bool {
	if c.Dataplane.VerifySysctls != nil {
		return *c.Dataplane.VerifySysctls
	}
	for _, l := range c.Links {
		if l.Interface != "" {
			return true
		}
	}
	return false
}

func applyDefaults(cfg *Config) {
	if cfg.Audit.RetainDays == 0 {
		cfg.Audit.RetainDays = DefaultAuditRetainDays
	}
	if cfg.Audit.MaxFileBytes == 0 {
		cfg.Audit.MaxFileBytes = DefaultAuditMaxFileBytes
	}
	if cfg.DNS.FakeCIDR == "" {
		cfg.DNS.FakeCIDR = DefaultFakeCIDR
	}
	if cfg.DNS.TTLSeconds == 0 {
		cfg.DNS.TTLSeconds = DefaultDNSTTLSeconds
	}
	if cfg.HTTP.MaxRequestBodyBytes == 0 {
		cfg.HTTP.MaxRequestBodyBytes = DefaultMaxRequestBodyBytes
	}
	if cfg.HTTP.WSMaxEgressBytes == 0 {
		cfg.HTTP.WSMaxEgressBytes = DefaultWSMaxEgressBytes
	}
	if cfg.HTTP.MaxHeaderBytes == 0 {
		cfg.HTTP.MaxHeaderBytes = DefaultMaxHeaderBytes
	}
	if cfg.Dataplane.DHCP.LeaseTime == "" {
		cfg.Dataplane.DHCP.LeaseTime = DefaultDHCPLeaseTime
	}
	for i := range cfg.Links {
		if cfg.Links[i].HTTPSPort == 0 {
			cfg.Links[i].HTTPSPort = DefaultHTTPSPort
		}
		if cfg.Links[i].HTTPPort == 0 {
			cfg.Links[i].HTTPPort = DefaultHTTPPort
		}
		if cfg.Links[i].DNSPort == 0 {
			cfg.Links[i].DNSPort = DefaultDNSPort
		}
		if cfg.Links[i].RoutePref == 0 && cfg.Links[i].RouteTable > 0 {
			cfg.Links[i].RoutePref = 1000 + i
		}
	}
	for i := range cfg.Rules {
		if len(cfg.Rules[i].Ports) == 0 {
			cfg.Rules[i].Ports = []uint16{443}
		}
	}
}

func validate(cfg *Config) error {
	if cfg.CA.CertPath == "" {
		return errors.New("ca.cert_path is required")
	}
	if cfg.CA.KeyPath == "" {
		return errors.New("ca.key_path is required")
	}
	if cfg.Audit.Dir == "" {
		return errors.New("audit.dir is required")
	}
	if cfg.Audit.RetainDays < 0 || cfg.Audit.RetainDays > MaxAuditRetainDays {
		return fmt.Errorf("audit.retain_days %d out of range [0, %d]", cfg.Audit.RetainDays, MaxAuditRetainDays)
	}
	if cfg.Audit.MaxFileBytes < 0 {
		return fmt.Errorf("audit.max_file_bytes must be >= 0, got %d", cfg.Audit.MaxFileBytes)
	}
	if cfg.Metrics.Listen != "" {
		if err := validateExplicitListenAddr(cfg.Metrics.Listen); err != nil {
			return fmt.Errorf("metrics.listen: %w", err)
		}
	}
	if err := validateDNS(cfg); err != nil {
		return err
	}
	if err := validateHTTP(cfg.HTTP); err != nil {
		return err
	}
	if err := validateRecords(cfg); err != nil {
		return err
	}
	declaredPrincipals, hasLinuxIf, err := validateLinks(cfg)
	if err != nil {
		return err
	}
	if hasLinuxIf {
		if cfg.Dataplane.ReadyFile == "" || !filepath.IsAbs(cfg.Dataplane.ReadyFile) {
			return fmt.Errorf("dataplane.ready_file %q must be an absolute path when any Linux link interface is configured", cfg.Dataplane.ReadyFile)
		}
		if err := validateDHCP(cfg.Dataplane.DHCP); err != nil {
			return err
		}
	}
	if err := validateRules(cfg, declaredPrincipals); err != nil {
		return err
	}
	return nil
}

func validateExplicitListenAddr(addr string) error {
	host, portStr, err := net.SplitHostPort(addr)
	if err != nil {
		return fmt.Errorf("invalid host:port %q: %w", addr, err)
	}
	if host == "" {
		return fmt.Errorf("wildcard listen address %q is forbidden", addr)
	}
	ip, err := netip.ParseAddr(host)
	if err != nil {
		return fmt.Errorf("listen host %q must be an explicit IP literal: %w", host, err)
	}
	ip = ip.Unmap()
	if ip.IsUnspecified() {
		return fmt.Errorf("wildcard listen address %q is forbidden", addr)
	}
	if portStr == "" {
		return fmt.Errorf("missing port in %q", addr)
	}
	return nil
}

func validateDNS(cfg *Config) error {
	p, err := netip.ParsePrefix(cfg.DNS.FakeCIDR)
	if err != nil {
		return fmt.Errorf("dns.fake_cidr %q: %w", cfg.DNS.FakeCIDR, err)
	}
	if !p.Addr().Is4() {
		return fmt.Errorf("dns.fake_cidr %q must be IPv4", cfg.DNS.FakeCIDR)
	}
	if p.Bits() > 30 {
		return fmt.Errorf("dns.fake_cidr %q must have prefix <= /30 (at least 2 usable addresses)", cfg.DNS.FakeCIDR)
	}
	cfg.FakePrefix = p.Masked()
	return nil
}

func validateHTTP(h HTTPConfig) error {
	if h.MaxRequestBodyBytes <= 0 {
		return fmt.Errorf("http.max_request_body_bytes must be > 0, got %d", h.MaxRequestBodyBytes)
	}
	if h.WSMaxEgressBytes <= 0 {
		return fmt.Errorf("http.ws_max_egress_bytes must be > 0, got %d", h.WSMaxEgressBytes)
	}
	if h.MaxHeaderBytes <= 0 {
		return fmt.Errorf("http.max_header_bytes must be > 0, got %d", h.MaxHeaderBytes)
	}
	return nil
}

func validateRecords(cfg *Config) error {
	cfg.ParsedRecords = make(map[string]netip.Addr, len(cfg.Records))
	for rawHost, rawIP := range cfg.Records {
		host, err := NormalizeExactHost(rawHost)
		if err != nil {
			return fmt.Errorf("records[%q]: %w", rawHost, err)
		}
		if _, dup := cfg.ParsedRecords[host]; dup {
			return fmt.Errorf("records: duplicate normalized host %q", host)
		}
		addr, err := netip.ParseAddr(strings.TrimSpace(rawIP))
		if err != nil {
			return fmt.Errorf("records[%q]: invalid IP %q: %w", rawHost, rawIP, err)
		}
		addr = addr.Unmap()
		if addr.IsUnspecified() || addr.IsMulticast() {
			return fmt.Errorf("records[%q]: IP %s must be unicast", rawHost, addr)
		}
		cfg.ParsedRecords[host] = addr
	}
	return nil
}

func validateLinks(cfg *Config) (map[string]bool, bool, error) {
	if len(cfg.Links) == 0 {
		return nil, false, errors.New("links: at least one link is required")
	}

	principals := make(map[string]bool, len(cfg.Links))
	seenNames := make(map[string]bool, len(cfg.Links))
	seenIfs := make(map[string]bool, len(cfg.Links))
	seenIPs := make(map[netip.Addr]bool, len(cfg.Links))
	seenZones := make(map[uint16]bool, len(cfg.Links))
	seenTables := make(map[int]bool, len(cfg.Links))
	var subnets []struct {
		name   string
		prefix netip.Prefix
	}
	hasLinuxIf := false

	for i := range cfg.Links {
		l := &cfg.Links[i]
		if l.Name == "" || !isSafeIdentifier(l.Name) {
			return nil, false, fmt.Errorf("links[%d].name %q is invalid", i, l.Name)
		}
		if seenNames[l.Name] {
			return nil, false, fmt.Errorf("links: duplicate link name %q", l.Name)
		}
		seenNames[l.Name] = true

		if l.Principal == "" || !isSafeIdentifier(l.Principal) {
			return nil, false, fmt.Errorf("links[%s].principal %q is invalid", l.Name, l.Principal)
		}
		principals[l.Principal] = true

		if l.Interface != "" {
			hasLinuxIf = true
			if !isValidIfName(l.Interface) {
				return nil, false, fmt.Errorf("links[%s].interface %q is invalid", l.Name, l.Interface)
			}
			if seenIfs[l.Interface] {
				return nil, false, fmt.Errorf("links: duplicate interface %q", l.Interface)
			}
			seenIfs[l.Interface] = true
			if l.CTZone == 0 {
				return nil, false, fmt.Errorf("links[%s].ct_zone must be > 0 when interface is set", l.Name)
			}
			if l.RouteTable <= 0 || l.RouteTable == 253 || l.RouteTable == 254 || l.RouteTable == 255 {
				return nil, false, fmt.Errorf("links[%s].route_table %d is invalid (reserved or <= 0)", l.Name, l.RouteTable)
			}
		}
		if l.CTZone > 0 {
			if seenZones[l.CTZone] {
				return nil, false, fmt.Errorf("links: duplicate ct_zone %d", l.CTZone)
			}
			seenZones[l.CTZone] = true
		}
		if l.RouteTable > 0 {
			if seenTables[l.RouteTable] {
				return nil, false, fmt.Errorf("links: duplicate route_table %d", l.RouteTable)
			}
			seenTables[l.RouteTable] = true
		}

		sub, err := netip.ParsePrefix(l.Subnet)
		if err != nil {
			return nil, false, fmt.Errorf("links[%s].subnet %q: %w", l.Name, l.Subnet, err)
		}
		if !sub.Addr().Is4() {
			return nil, false, fmt.Errorf("links[%s].subnet %q must be IPv4", l.Name, l.Subnet)
		}
		if sub.Bits() > 29 {
			return nil, false, fmt.Errorf("links[%s].subnet %q must be /29 or larger for multi-address DHCP pool", l.Name, l.Subnet)
		}
		sub = sub.Masked()
		l.ParsedSubnet = sub

		for _, prev := range subnets {
			if prev.prefix.Overlaps(sub) {
				return nil, false, fmt.Errorf("links: subnet %s on %q overlaps subnet %s on %q", sub, l.Name, prev.prefix, prev.name)
			}
		}
		subnets = append(subnets, struct {
			name   string
			prefix netip.Prefix
		}{name: l.Name, prefix: sub})

		gwIP, err := netip.ParseAddr(l.GatewayIP)
		if err != nil {
			return nil, false, fmt.Errorf("links[%s].gateway_ip %q: %w", l.Name, l.GatewayIP, err)
		}
		gwIP = gwIP.Unmap()
		if !gwIP.Is4() || gwIP.IsUnspecified() || gwIP.IsMulticast() {
			return nil, false, fmt.Errorf("links[%s].gateway_ip %q must be an explicit unicast IPv4 address", l.Name, l.GatewayIP)
		}
		if !sub.Contains(gwIP) {
			return nil, false, fmt.Errorf("links[%s].gateway_ip %s must be inside subnet %s", l.Name, gwIP, sub)
		}
		if gwIP == sub.Addr() || gwIP == broadcastIPv4(sub) {
			return nil, false, fmt.Errorf("links[%s].gateway_ip %s cannot be subnet network or broadcast address", l.Name, gwIP)
		}
		if seenIPs[gwIP] {
			return nil, false, fmt.Errorf("links: duplicate gateway_ip %s", gwIP)
		}
		seenIPs[gwIP] = true
		l.ParsedGatewayIP = gwIP

		if l.HTTPSPort < 1024 || l.HTTPPort < 1024 || l.DNSPort < 1024 {
			return nil, false, fmt.Errorf("links[%s]: listener ports must be >= 1024 (got https=%d http=%d dns=%d)", l.Name, l.HTTPSPort, l.HTTPPort, l.DNSPort)
		}
		if l.HTTPSPort == l.HTTPPort || l.HTTPSPort == l.DNSPort || l.HTTPPort == l.DNSPort {
			return nil, false, fmt.Errorf("links[%s]: https_port, http_port, and dns_port must be distinct", l.Name)
		}
	}
	return principals, hasLinuxIf, nil
}

func validateDHCP(d DHCPConfig) error {
	if d.User == "" || !isSafeIdentifier(d.User) {
		return fmt.Errorf("dataplane.dhcp.user %q is required and must be a valid username when sandbox interfaces are configured", d.User)
	}
	if d.LeaseFile == "" || !filepath.IsAbs(d.LeaseFile) {
		return fmt.Errorf("dataplane.dhcp.lease_file %q must be an absolute path when sandbox interfaces are configured", d.LeaseFile)
	}
	if d.ConfigPath != "" && !filepath.IsAbs(d.ConfigPath) {
		return fmt.Errorf("dataplane.dhcp.config_path %q must be an absolute path", d.ConfigPath)
	}
	if d.LeaseTime != "infinite" {
		if dur, err := time.ParseDuration(d.LeaseTime); err != nil || dur < time.Minute {
			return fmt.Errorf("dataplane.dhcp.lease_time %q must be a valid duration >= 1m", d.LeaseTime)
		}
	}
	return nil
}

func validateRules(cfg *Config, declaredPrincipals map[string]bool) error {
	seenIDs := make(map[string]bool, len(cfg.Rules))
	seenPlaceholders := make(map[string]string)
	type principalHost struct {
		principal string
		host      string
	}
	boundHosts := make(map[principalHost]string)
	wsHosts := make(map[principalHost]string)

	for i := range cfg.Rules {
		r := &cfg.Rules[i]
		if r.ID == "" || !isSafeIdentifier(r.ID) {
			return fmt.Errorf("rules[%d].id %q is invalid", i, r.ID)
		}
		if seenIDs[r.ID] {
			return fmt.Errorf("rules: duplicate rule id %q", r.ID)
		}
		seenIDs[r.ID] = true

		if !declaredPrincipals[r.Principal] {
			return fmt.Errorf("rules[%s].principal %q does not match any declared link", r.ID, r.Principal)
		}
		if r.Effect != "allow" && r.Effect != "deny" {
			return fmt.Errorf("rules[%s].effect %q must be allow or deny", r.ID, r.Effect)
		}
		if len(r.Hosts) == 0 {
			return fmt.Errorf("rules[%s].hosts must not be empty", r.ID)
		}
		normHosts := make([]string, len(r.Hosts))
		seenHosts := make(map[string]bool, len(r.Hosts))
		for hi, raw := range r.Hosts {
			nh, err := NormalizeHostPattern(raw)
			if err != nil {
				return fmt.Errorf("rules[%s].hosts[%d]: %w", r.ID, hi, err)
			}
			if seenHosts[nh] {
				return fmt.Errorf("rules[%s].hosts: duplicate host %q", r.ID, nh)
			}
			seenHosts[nh] = true
			normHosts[hi] = nh
		}
		r.Hosts = normHosts

		seenPorts := make(map[uint16]bool, len(r.Ports))
		has443 := false
		for _, p := range r.Ports {
			if p != 80 && p != 443 {
				return fmt.Errorf("rules[%s].ports: port %d is forbidden (only 80 and 443 are permitted)", r.ID, p)
			}
			if seenPorts[p] {
				return fmt.Errorf("rules[%s].ports: duplicate port %d", r.ID, p)
			}
			seenPorts[p] = true
			if p == 443 {
				has443 = true
			}
		}

		for mi, m := range r.Methods {
			if !isValidHTTPMethod(m) {
				return fmt.Errorf("rules[%s].methods[%d] %q is invalid", r.ID, mi, m)
			}
			r.Methods[mi] = strings.ToUpper(m)
		}
		for pi, p := range r.Paths {
			if !strings.HasPrefix(p, "/") {
				return fmt.Errorf("rules[%s].paths[%d] %q must start with '/'", r.ID, pi, p)
			}
		}

		if r.WSMaxEgressBytes < 0 {
			return fmt.Errorf("rules[%s].ws_max_egress_bytes must be >= 0", r.ID)
		}
		if len(r.Bindings) > 0 && r.AllowWebSocket {
			return fmt.Errorf("rules[%s]: a rule with bindings cannot set allow_websocket", r.ID)
		}
		if len(r.Bindings) > 0 && r.Effect != "allow" {
			return fmt.Errorf("rules[%s]: bindings are only valid on allow rules", r.ID)
		}
		if len(r.Bindings) > 0 && !has443 {
			return fmt.Errorf("rules[%s]: bindings require port 443 (cleartext port 80 does not substitute secrets)", r.ID)
		}

		if r.AllowWebSocket {
			for _, h := range r.Hosts {
				wsHosts[principalHost{principal: r.Principal, host: h}] = r.ID
			}
		}

		seenBindings := make(map[string]bool, len(r.Bindings))
		for bi := range r.Bindings {
			b := &r.Bindings[bi]
			if err := validateBinding(r.ID, b, seenHosts); err != nil {
				return err
			}
			if seenBindings[b.Name] {
				return fmt.Errorf("rules[%s].bindings: duplicate binding name %q", r.ID, b.Name)
			}
			seenBindings[b.Name] = true
			if prevRule, dup := seenPlaceholders[b.Placeholder]; dup {
				return fmt.Errorf("rules[%s].bindings[%s]: duplicate placeholder %q (already used by rule %q)", r.ID, b.Name, b.Placeholder, prevRule)
			}
			seenPlaceholders[b.Placeholder] = r.ID
			boundHosts[principalHost{principal: r.Principal, host: b.Host}] = r.ID
		}
	}

	// Cross-rule safety check: a host with a binding for a principal must not also
	// have allow_websocket enabled on another rule for the same principal.
	for bh, bRuleID := range boundHosts {
		for wh, wRuleID := range wsHosts {
			if bh.principal != wh.principal {
				continue
			}
			if bh.host == wh.host || wildcardMatches(wh.host, bh.host) {
				return fmt.Errorf("rules[%s]: allow_websocket on %q conflicts with binding on host %q in rule %q for principal %q",
					wRuleID, wh.host, bh.host, bRuleID, bh.principal)
			}
		}
	}
	return nil
}

func validateBinding(ruleID string, b *BindingConfig, ruleHosts map[string]bool) error {
	if b.Name == "" || !isSafeIdentifier(b.Name) {
		return fmt.Errorf("rules[%s].bindings: invalid name %q", ruleID, b.Name)
	}
	host, err := NormalizeExactHost(b.Host)
	if err != nil {
		return fmt.Errorf("rules[%s].bindings[%s].host: %w", ruleID, b.Name, err)
	}
	if !ruleHosts[host] {
		return fmt.Errorf("rules[%s].bindings[%s].host %q must be one of the rule's hosts", ruleID, b.Name, host)
	}
	b.Host = host

	for mi, m := range b.Methods {
		if !isValidHTTPMethod(m) {
			return fmt.Errorf("rules[%s].bindings[%s].methods[%d] %q is invalid", ruleID, b.Name, mi, m)
		}
		b.Methods[mi] = strings.ToUpper(m)
	}
	for pi, p := range b.Paths {
		if !strings.HasPrefix(p, "/") {
			return fmt.Errorf("rules[%s].bindings[%s].paths[%d] %q must start with '/'", ruleID, b.Name, pi, p)
		}
	}

	canon := textproto.CanonicalMIMEHeaderKey(strings.TrimSpace(b.Header))
	if canon == "" || !isValidHeaderName(canon) {
		return fmt.Errorf("rules[%s].bindings[%s].header %q is invalid", ruleID, b.Name, b.Header)
	}
	switch canon {
	case "Host", "Content-Length", "Transfer-Encoding", "Connection", "Proxy-Authorization":
		return fmt.Errorf("rules[%s].bindings[%s].header %q is forbidden", ruleID, b.Name, canon)
	}
	b.Header = canon

	scheme := strings.ToLower(strings.TrimSpace(b.Scheme))
	switch scheme {
	case "bearer", "basic", "token", "raw":
		b.Scheme = scheme
	default:
		return fmt.Errorf("rules[%s].bindings[%s].scheme %q must be one of bearer, basic, token, raw", ruleID, b.Name, b.Scheme)
	}

	if !strings.HasPrefix(b.Placeholder, PlaceholderPrefix) || len(b.Placeholder) <= len(PlaceholderPrefix) {
		return fmt.Errorf("rules[%s].bindings[%s].placeholder %q must start with %q and have a non-empty suffix", ruleID, b.Name, b.Placeholder, PlaceholderPrefix)
	}
	for _, r := range b.Placeholder {
		if r <= 0x20 || r >= 0x7f {
			return fmt.Errorf("rules[%s].bindings[%s].placeholder contains non-printable or whitespace character", ruleID, b.Name)
		}
	}

	if b.SecretFile == "" || !filepath.IsAbs(b.SecretFile) {
		return fmt.Errorf("rules[%s].bindings[%s].secret_file %q must be an absolute path", ruleID, b.Name, b.SecretFile)
	}
	return nil
}

// NormalizeHost trims surrounding whitespace, lowercases, and strips a single trailing dot.
func NormalizeHost(raw string) string {
	return strings.TrimSuffix(strings.ToLower(strings.TrimSpace(raw)), ".")
}

// NormalizeExactHost validates and lowercases an exact DNS hostname (no wildcard, no IP literal).
func NormalizeExactHost(raw string) (string, error) {
	h := NormalizeHost(raw)
	if h == "" {
		return "", errors.New("empty hostname")
	}
	if strings.Contains(h, "*") {
		return "", fmt.Errorf("wildcard host %q is not allowed here", raw)
	}
	if _, err := netip.ParseAddr(h); err == nil {
		return "", fmt.Errorf("IP literal %q is not allowed as a hostname", raw)
	}
	if err := validateHostnameLabels(h); err != nil {
		return "", fmt.Errorf("invalid hostname %q: %w", raw, err)
	}
	return h, nil
}

// NormalizeHostPattern validates an exact hostname or single leading wildcard (*.zone).
func NormalizeHostPattern(raw string) (string, error) {
	h := NormalizeHost(raw)
	if h == "" {
		return "", errors.New("empty host pattern")
	}
	if strings.HasPrefix(h, "*.") {
		rest := h[2:]
		if strings.Contains(rest, "*") {
			return "", fmt.Errorf("invalid wildcard pattern %q: only a single leading *. is allowed", raw)
		}
		if strings.Count(rest, ".") < 1 {
			return "", fmt.Errorf("wildcard pattern %q is too broad (must include at least two labels after *.)", raw)
		}
		if err := validateHostnameLabels(rest); err != nil {
			return "", fmt.Errorf("invalid wildcard host %q: %w", raw, err)
		}
		return "*." + rest, nil
	}
	return NormalizeExactHost(h)
}

func validateHostnameLabels(h string) error {
	if len(h) > 253 {
		return errors.New("exceeds 253 bytes")
	}
	labels := strings.Split(h, ".")
	for _, label := range labels {
		if len(label) == 0 || len(label) > 63 {
			return errors.New("empty or overlong label")
		}
		if label[0] == '-' || label[len(label)-1] == '-' {
			return errors.New("label cannot start or end with '-'")
		}
		for i := 0; i < len(label); i++ {
			if !isHostLabelByte(label[i]) {
				return fmt.Errorf("illegal character %q", label[i])
			}
		}
	}
	return nil
}

func isHostLabelByte(c byte) bool {
	return (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '-' || c == '_'
}

func isIdentByte(c byte) bool {
	return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '-' || c == '_' || c == '.'
}

func isTokenByte(c byte) bool {
	return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '-' || c == '_'
}

func wildcardMatches(pattern, host string) bool {
	if !strings.HasPrefix(pattern, "*.") {
		return false
	}
	suffix := pattern[1:] // ".zone"
	return strings.HasSuffix(host, suffix) && len(host) > len(suffix)
}

func broadcastIPv4(p netip.Prefix) netip.Addr {
	b := p.Masked().Addr().As4()
	hostBits := 32 - p.Bits()
	mask := uint32(1<<hostBits) - 1
	ip := uint32(b[0])<<24 | uint32(b[1])<<16 | uint32(b[2])<<8 | uint32(b[3])
	bcast := ip | mask
	return netip.AddrFrom4([4]byte{byte(bcast >> 24), byte(bcast >> 16), byte(bcast >> 8), byte(bcast)})
}

func isSafeIdentifier(s string) bool {
	if len(s) == 0 || len(s) > 64 {
		return false
	}
	for i := 0; i < len(s); i++ {
		if !isIdentByte(s[i]) {
			return false
		}
	}
	return true
}

func isValidIfName(s string) bool {
	// Linux IFNAMSIZ is 16 including NUL terminator; '.' is rejected in v0.1 because
	// sysctl paths map '.' to '/'.
	if len(s) == 0 || len(s) > 15 {
		return false
	}
	for i := 0; i < len(s); i++ {
		if !isTokenByte(s[i]) {
			return false
		}
	}
	return true
}

func isValidHTTPMethod(m string) bool {
	if m == "" {
		return false
	}
	for i := 0; i < len(m); i++ {
		if !isTokenByte(m[i]) {
			return false
		}
	}
	return true
}

func isValidHeaderName(h string) bool {
	if h == "" {
		return false
	}
	for i := 0; i < len(h); i++ {
		if !isTokenByte(h[i]) {
			return false
		}
	}
	return true
}
